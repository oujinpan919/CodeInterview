package com.codeinterview.ai.controller;

import java.util.ArrayList;
import java.util.List;

import org.springframework.web.bind.annotation.DeleteMapping;
import org.springframework.web.bind.annotation.GetMapping;
import org.springframework.web.bind.annotation.PathVariable;
import org.springframework.web.bind.annotation.PostMapping;
import org.springframework.web.bind.annotation.PutMapping;
import org.springframework.web.bind.annotation.RequestBody;
import org.springframework.web.bind.annotation.RequestMapping;
import org.springframework.web.bind.annotation.RestController;

import com.codeinterview.ai.config.MasterKeyProvider;
import com.codeinterview.ai.config.ModelConfigResolver;
import com.codeinterview.ai.entity.SiteModelConfig;
import com.codeinterview.ai.entity.UserModelConfig;
import com.codeinterview.ai.mapper.SiteModelConfigMapper;
import com.codeinterview.ai.mapper.UserModelConfigMapper;
import com.codeinterview.ai.service.PromptTemplateService;
import com.codeinterview.ai.vo.ActiveModelResp;
import com.codeinterview.ai.vo.ChatPageMetaResp;
import com.codeinterview.ai.vo.PromptTemplateResp;
import com.codeinterview.common.exception.BusinessException;
