import io.swagger.v3.oas.annotations.tags.Tag;
import lombok.RequiredArgsConstructor;

/**
 * 对话页元数据（D2/D13/D11）：一次请求拿全模型列表 + 生效模型 + 模板 + 开关状态。
 *
 * <p>放在 /ai 下而不复用 /ai/config，是因为对话页只需要「可选项」，
 * 不需要凭证掩码等配置页信息。
 */
@Tag(name = "AI 对话页元数据")
@RestController
@RequestMapping("/api/v1/ai")
@RequiredArgsConstructor
public class AiMetaController {

    private final UserModelConfigMapper userConfigMapper;
    private final SiteModelConfigMapper siteConfigMapper;
    private final ModelConfigResolver resolver;
    private final PromptTemplateService promptTemplateService;
    private final MasterKeyProvider masterKeyProvider;

    @Operation(summary = "对话页初始化：可用模型 + 生效模型 + 模板 + 开关")
    @GetMapping("/meta")
    public Result<ChatPageMetaResp> meta() {
        Long userId = StpUtil.getLoginIdAsLong();
        boolean allowOwn = resolver.allowUserOwnKey();

        List<ActiveModelResp> models = new ArrayList<>();
        if (allowOwn) {
            for (UserModelConfig config : userConfigMapper.selectAll(userId)) {
                if (config.getIsEnabled() != null && config.getIsEnabled() == 1) {
                    models.add(toActive(config.getId(), config.getDisplayName(), config.getModelId(),
                            config.getProviderType(), config.getIsDefault() != null && config.getIsDefault() == 1,
                            "USER_OWN", false));
                }
            }
        }
        SiteModelConfig site = siteConfigMapper.selectActive();
        if (site != null) {
            models.add(toActive(site.getId(), site.getDisplayName(), site.getModelId(),
                    site.getProviderType(), true, "SITE_DEFAULT", true));
        }

        ModelConfigResolver.Resolved active = resolver.resolve(userId, null);

        ChatPageMetaResp resp = new ChatPageMetaResp();
        resp.setModels(models);
        if (active != null) {
            resp.setActiveModelConfigId(active.configId());
            resp.setResolvedFrom(active.from().name());
        }
        resp.setAllowUserOwnKey(allowOwn);
        resp.setHasAnyUsableConfig(active != null);
        resp.setMasterKeyAutoGenerated(masterKeyProvider.isAutoGenerated());
        resp.setTemplates(promptTemplateService.listEnabled());
        return Result.success(resp);
    }

    @Operation(summary = "Prompt 模板列表（仅启用项，不含正文）")
    @GetMapping("/templates")
    public Result<List<PromptTemplateResp>> templates() {
        return Result.success(promptTemplateService.listEnabled());
    }

    // ---- 主密钥导出（D3-b：仅管理员，不进日志，no-store）----

    @Operation(summary = "导出主密钥（仅管理员，用于换机/备份恢复）")
    @GetMapping("/master-key")
    public Result<MasterKeyExportResp> exportMasterKey() {
        if (!StpUtil.hasRole("ADMIN")) {
            throw new BusinessException(ResultCode.ADMIN_REQUIRED);
        }
        MasterKeyExportResp resp = new MasterKeyExportResp();
        resp.setBase64(masterKeyProvider.exportBase64());
        resp.setAutoGenerated(masterKeyProvider.isAutoGenerated());
        resp.setNotice("请妥善备份：换机或从备份恢复数据库时需要同一个主密钥，否则已保存的凭证将无法解密");
        return Result.success(resp);
    }

    private ActiveModelResp toActive(Long id, String displayName, String modelId, String providerType,
                                     boolean isDefault, String resolvedFrom, boolean consumesSite) {
        ActiveModelResp resp = new ActiveModelResp();
        resp.setId(id);
        resp.setDisplayName(displayName);
        resp.setModelId(modelId);
        resp.setProviderType(providerType);
        resp.setIsDefault(isDefault);
        resp.setIsEnabled(true);
        resp.setResolvedFrom(resolvedFrom);
        resp.setConsumsesSiteQuota(consumesSite);
        return resp;
    }

    @lombok.Data
    public static class MasterKeyExportResp {
        private String base64;
        private Boolean autoGenerated;
        private String notice;
    }
}
