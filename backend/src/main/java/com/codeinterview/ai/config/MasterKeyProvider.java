package com.codeinterview.ai.config;

import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.Paths;
import java.security.SecureRandom;
import java.util.Base64;
import java.util.LinkedHashMap;

import org.springframework.core.env.Environment;
import org.springframework.stereotype.Component;

import lombok.extern.slf4j.Slf4j;

/**
 * 主密钥加载与生成（D3-a/b / 08 §7 S4）。
 *
 * <p>取值优先级：环境变量 {@code APP_ENCRYPT_KEY} &gt; 配置文件 {@code app.encrypt.key}。
 * 都取不到时<b>自动生成</b>一枚 32 字节密钥并写入 {@code ./config/application-local.yml}
 * （该文件已 gitignore），同时打 WARN —— 避免既有部署升级后配置页直接不可用。
 *
 * <p>注意：自动生成的密钥只对本机当前这份库有效。换机或从备份恢复数据库后，
 * 旧密文将<b>无法解密</b>，因此配置页需常驻备份提示（见 {@code AiConfigController#exportKey}）。
 */
@Slf4j
@Component
public class MasterKeyProvider {

    public static final String ENV_KEY = "APP_ENCRYPT_KEY";
    private static final String LOCAL_FILE = "./config/application-local.yml";
    private static final int KEY_BYTES = 32;
    private static final String PLACEHOLDER = "app:\n  encrypt:\n    key: %s\n";

    private final byte[] key;
    private final boolean autoGenerated;

    public MasterKeyProvider(Environment environment) {
        String configured = firstNonBlank(environment.getProperty(ENV_KEY), environment.getProperty("app.encrypt.key"));
        if (configured != null) {
            this.key = decode(configured);
            this.autoGenerated = false;
            log.info("[ai-config] master key loaded from configuration, version=1");
        } else {
            if (isProdProfile(environment)) {
                throw new IllegalStateException(
                        ENV_KEY + " 在生产环境必须显式配置；禁止自动生成到容器临时层，"
                                + "否则重建/换机后已保存的用户 AI 凭证将全部无法解密。");
            }
            this.key = generate();
            this.autoGenerated = true;
            persist(this.key);
            log.warn("[ai-config] {} 未配置，已自动生成主密钥并写入 {}；请自行备份，否则换机/恢复备份后已存凭证将无法解密",
                    ENV_KEY, LOCAL_FILE);
        }
    }

    private boolean isProdProfile(Environment environment) {
        for (String profile : environment.getActiveProfiles()) {
            if ("prod".equalsIgnoreCase(profile)) {
                return true;
            }
        }
        return false;
    }

    /** 当前主密钥（副本，调用方不得持有引用）。 */
    public byte[] key() {
        return key.clone();
    }

    /** 主密钥版本号；本期固定 1，轮换时递增。 */
    public int keyVersion() {
        return 1;
    }

    /** 是否为自动生成的密钥（配置页据此显示备份横幅）。 */
    public boolean isAutoGenerated() {
        return autoGenerated;
    }

    /** 导出用：Base64 编码的主密钥。 */
    public String exportBase64() {
        return Base64.getEncoder().encodeToString(key);
    }

    private byte[] generate() {
        byte[] generated = new byte[KEY_BYTES];
        new SecureRandom().nextBytes(generated);
        return generated;
    }

    /** 支持 Base64（44 字符）与 64 位十六进制两种写法。 */
    private byte[] decode(String raw) {
        String value = raw.trim();
        byte[] decoded;
        if (value.length() == KEY_BYTES * 2 && value.matches("[0-9a-fA-F]+")) {
            decoded = hexDecode(value);
        } else {
            try {
                decoded = Base64.getDecoder().decode(value);
            } catch (IllegalArgumentException ex) {
                throw new IllegalStateException(ENV_KEY + " 不是合法的 Base64 或十六进制字符串", ex);
            }
        }
        if (decoded.length != KEY_BYTES) {
            throw new IllegalStateException(ENV_KEY + " 长度必须为 " + KEY_BYTES + " 字节（AES-256），实际 " + decoded.length);
        }
        return decoded;
    }

    private byte[] hexDecode(String hex) {
        byte[] out = new byte[hex.length() / 2];
        for (int i = 0; i < out.length; i++) {
            out[i] = (byte) Integer.parseInt(hex.substring(i * 2, i * 2 + 2), 16);
        }
        return out;
    }

    /**
     * 把自动生成的密钥追加到本机配置文件。写失败只打 WARN，不影响启动
     * （此时密钥仅存在于进程内存，重启即失效，用户会在配置页看到提示）。
     */
    private void persist(byte[] generated) {
        String encoded = Base64.getEncoder().encodeToString(generated);
        try {
            Path path = Paths.get(LOCAL_FILE);
            Files.createDirectories(path.getParent());
            String existing = Files.exists(path) ? Files.readString(path, StandardCharsets.UTF_8) : "";
            if (existing.contains("encrypt:")) {
                log.warn("[ai-config] {} 已存在 encrypt 段，跳过写入以免覆盖", LOCAL_FILE);
                return;
            }
            StringBuilder builder = new StringBuilder(existing);
            if (!existing.isBlank() && !existing.endsWith("\n")) {
                builder.append('\n');
            }
            builder.append('\n').append(PLACEHOLDER.formatted(encoded));
            Files.writeString(path, builder.toString(), StandardCharsets.UTF_8);
        } catch (IOException ex) {
            log.warn("[ai-config] 无法写入 {}（{}），主密钥仅存在于进程内存，重启后需重新配置凭证",
                    LOCAL_FILE, ex.getMessage());
        }
    }

    private String firstNonBlank(String... values) {
        for (String value : values) {
            if (value != null && !value.isBlank()) {
                return value;
            }
        }
        return null;
    }

    /** 供测试/诊断：脱敏描述。 */
    public String describe() {
        var info = new LinkedHashMap<String, Object>();
        info.put("autoGenerated", autoGenerated);
        info.put("keyVersion", keyVersion());
        return info.toString();
    }
}
